-- Háztartásonként és naponként legfeljebb egy emlékeztető-levél. Az egyedi megkötés akkor is
-- véd a dupla küldés ellen, ha a job két példányban (több szerveren, újraindításkor) fut.
CREATE TABLE reminder_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id    BIGINT      NOT NULL,
    reminder_date   DATE        NOT NULL,
    recipient_count INTEGER     NOT NULL,
    deadline_count  INTEGER     NOT NULL,
    sent_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_reminder_log_household FOREIGN KEY (household_id) REFERENCES household (id),
    CONSTRAINT uq_reminder_log_household_date UNIQUE (household_id, reminder_date),
    CONSTRAINT ck_reminder_log_counts CHECK (recipient_count > 0 AND deadline_count > 0)
);
-- Az FK-oszlop indexét a uq_reminder_log_household_date (household_id, reminder_date) lefedi.

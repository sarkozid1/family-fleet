-- =========================================================
-- V1: Kezdő séma – háztartás, tagok, járművek, biztosítás, határidők
-- =========================================================

CREATE TABLE household (
                           id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name        VARCHAR(100) NOT NULL,
                           created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE household_member (
                                  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  household_id  BIGINT       NOT NULL REFERENCES household (id),
                                  name          VARCHAR(100) NOT NULL,
                                  email         VARCHAR(255),
                                  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_member_household ON household_member (household_id);

CREATE TABLE vehicle (
                         id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         household_id     BIGINT      NOT NULL REFERENCES household (id),
                         owner_id         BIGINT      REFERENCES household_member (id),
                         type             VARCHAR(20) NOT NULL CHECK (type IN ('CAR', 'MOTORCYCLE')),
                         brand            VARCHAR(50) NOT NULL,
                         model            VARCHAR(50) NOT NULL,
                         license_plate    VARCHAR(10) NOT NULL,
                         vin              VARCHAR(17),
                         production_year  SMALLINT    CHECK (production_year BETWEEN 1900 AND 2100),
                         current_mileage  INTEGER     NOT NULL DEFAULT 0 CHECK (current_mileage >= 0),
                         version          BIGINT      NOT NULL DEFAULT 0,
                         created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
                         updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
                         CONSTRAINT uq_vehicle_household_plate UNIQUE (household_id, license_plate)
);
CREATE INDEX idx_vehicle_owner ON vehicle (owner_id);

CREATE TABLE insurer (
                         id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         name     VARCHAR(100) NOT NULL UNIQUE,
                         phone    VARCHAR(30),
                         website  VARCHAR(255)
);

CREATE TABLE insurance_policy (
                                  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  vehicle_id         BIGINT        NOT NULL REFERENCES vehicle (id),
                                  insurer_id         BIGINT        NOT NULL REFERENCES insurer (id),
                                  policy_type        VARCHAR(20)   NOT NULL CHECK (policy_type IN ('KGFB', 'CASCO')),
                                  policy_number      VARCHAR(50),
                                  start_date         DATE          NOT NULL,
                                  end_date           DATE,
                                  annual_premium     NUMERIC(12,2) NOT NULL CHECK (annual_premium >= 0),
                                  payment_frequency  VARCHAR(20)   NOT NULL
                                      CHECK (payment_frequency IN ('ANNUAL', 'SEMI_ANNUAL', 'QUARTERLY', 'MONTHLY')),
                                  version            BIGINT        NOT NULL DEFAULT 0,
                                  created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                  updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
                                  CONSTRAINT ck_policy_dates CHECK (end_date IS NULL OR end_date > start_date)
);
CREATE INDEX idx_policy_vehicle ON insurance_policy (vehicle_id);
CREATE INDEX idx_policy_insurer ON insurance_policy (insurer_id);

CREATE TABLE deadline (
                          id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          household_id  BIGINT      NOT NULL REFERENCES household (id),
                          vehicle_id    BIGINT      REFERENCES vehicle (id),
                          member_id     BIGINT      REFERENCES household_member (id),
                          policy_id     BIGINT      REFERENCES insurance_policy (id),
                          type          VARCHAR(30) NOT NULL CHECK (type IN (
                                                                             'TECHNICAL_INSPECTION', 'INSURANCE_PAYMENT', 'KGFB_ANNIVERSARY',
                                                                             'VEHICLE_TAX', 'MOTORWAY_VIGNETTE', 'OIL_CHANGE',
                                                                             'TIRE_CHANGE', 'DRIVING_LICENCE', 'OTHER')),
                          title         VARCHAR(200),
                          due_date      DATE        NOT NULL,
                          status        VARCHAR(20) NOT NULL DEFAULT 'OPEN'
                              CHECK (status IN ('OPEN', 'DONE', 'DISMISSED')),
                          completed_at  TIMESTAMPTZ,
                          note          TEXT,
                          version       BIGINT      NOT NULL DEFAULT 0,
                          created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
                          updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_deadline_vehicle ON deadline (vehicle_id);
CREATE INDEX idx_deadline_member  ON deadline (member_id);
CREATE INDEX idx_deadline_policy  ON deadline (policy_id);

-- Részleges index: csak a nyitott határidőket indexeli, ez a leggyakoribb lekérdezés
-- ("mi jár le a következő 30 napban a háztartásban?")
CREATE INDEX idx_deadline_open_due ON deadline (household_id, due_date)
    WHERE status = 'OPEN';
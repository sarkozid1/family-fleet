-- A felhasználó (aki bejelentkezik) és a családtag (household_member, akiről nyilvántartunk,
-- pl. egy gyerek jogosítványa) két külön fogalom, ezért külön tábla.
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    -- {bcrypt}$2a$10$... formátum: az előtag jelzi az algoritmust (DelegatingPasswordEncoder)
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_app_user_email_lowercase CHECK (email = lower(email))
);

-- Ki melyik háztartáshoz fér hozzá. A létrehozó automatikusan hozzáférést kap.
CREATE TABLE household_access (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL,
    household_id BIGINT      NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_household_access_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_household_access_household FOREIGN KEY (household_id) REFERENCES household (id),
    CONSTRAINT uq_household_access_user_household UNIQUE (user_id, household_id)
);
-- A user_id-t a uq_household_access_user_household (user_id, household_id) index lefedi.
CREATE INDEX idx_household_access_household ON household_access (household_id);

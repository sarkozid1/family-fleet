-- Meghívó egy még nem regisztrált e-mail-címre. Regisztrációkor a meghívóból hozzáférés
-- (household_access) lesz, a meghívó pedig törlődik. A meghívó egyben engedély is a
-- regisztrációra, ha az éles környezetben a regisztráció zárt.
CREATE TABLE household_invitation (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id       BIGINT       NOT NULL,
    email              VARCHAR(255) NOT NULL,
    invited_by_user_id BIGINT       NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_household_invitation_household FOREIGN KEY (household_id) REFERENCES household (id),
    CONSTRAINT fk_household_invitation_invited_by FOREIGN KEY (invited_by_user_id) REFERENCES app_user (id),
    CONSTRAINT uq_household_invitation_household_email UNIQUE (household_id, email),
    CONSTRAINT ck_household_invitation_email_lowercase CHECK (email = lower(email))
);
-- household_id-t a uq_household_invitation_household_email lefedi; regisztrációkor e-mail szerint keresünk.
CREATE INDEX idx_household_invitation_email ON household_invitation (email);
CREATE INDEX idx_household_invitation_invited_by ON household_invitation (invited_by_user_id);
